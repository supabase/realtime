defmodule PolicyEval.Postgres.FixturesTest do
  # The parser reads the text that Postgres prints with pg_get_expr, so the library tests run on
  # captured output: the fixtures in test/fixtures, one per major version. This test captures the
  # output again and fails when it differs from the fixture of the running version. That is how a
  # change between versions shows up.
  #
  #   POLICY_EVAL_DATABASE_URL=... mix test test/postgres/fixtures_test.exs
  #   POLICY_EVAL_DATABASE_URL=... POLICY_EVAL_WRITE_FIXTURES=1 mix test test/postgres/fixtures_test.exs
  #
  # test_helper.exs excludes this test for a version that has no fixture, unless it writes them.
  # `--only postgres` includes it again, because an include wins over an exclude in ExUnit.
  #
  # Not async: the tests against Postgres share one database and change the same table, functions
  # and roles in it. Even in transactions that roll back, they would block or fail each other.
  use ExUnit.Case, async: false

  alias PolicyEval.Test.Postgres
  alias PolicyEval.Test.ExampleDatabase
  alias PolicyEval.Test.ExamplePolicies
  alias PolicyEval.Test.ExampleProfile

  @moduletag :postgres
  @moduletag :fixtures

  setup do
    %{conn: start_supervised!(Postgres)}
  end

  test "Postgres prints the policies and the functions as in the fixture of its version", %{conn: conn} do
    actual =
      Postgres.rolled_back(conn, fn conn ->
        statements =
          ExamplePolicies.personal_team_policies() ++
            ExamplePolicies.grammar_policies() ++ ExamplePolicies.typical_statements()

        Enum.each(statements, &Postgrex.query!(conn, &1, []))

        %{
          functions: Postgres.read_functions(conn, ExampleProfile.profile()),
          policies: Postgres.read_policies(conn, ExampleDatabase.table())
        }
      end)

    path = conn |> Postgres.server_version_num() |> div(10_000) |> Postgres.fixture_path()

    if System.get_env("POLICY_EVAL_WRITE_FIXTURES") == "1" do
      write_fixture!(path, actual)
    else
      unless File.exists?(path) do
        flunk("""
        No fixture for this Postgres at #{Path.relative_to_cwd(path)}.
        Generate it with: POLICY_EVAL_WRITE_FIXTURES=1 mix test test/postgres/fixtures_test.exs
        """)
      end

      {expected, _binding} = Code.eval_file(path)

      # Section by section, so a failure shows only what differs
      assert Map.keys(actual) == Map.keys(expected)
      assert actual.functions == expected.functions
      assert actual.policies == expected.policies
    end
  end

  defp write_fixture!(path, actual) do
    formatted =
      actual
      # Sorted, or the key order changes from one run to the next and so does the diff
      |> inspect(pretty: true, limit: :infinity, printable_limit: :infinity, custom_options: [sort_maps: true])
      |> Code.format_string!(line_length: 120)

    File.mkdir_p!(Path.dirname(path))
    File.write!(path, [header(), formatted, "\n"])
  end

  defp header do
    """
    # What Postgres prints for the policies of test/support/example_policies.ex, and for the
    # functions that they call, as test/support/example_database.ex creates them. Generated by
    # test/postgres/fixtures_test.exs. Do not edit it by hand.
    #
    # To generate it again, run the test against a Postgres of this major version, with
    # POLICY_EVAL_DATABASE_URL set as the README tells:
    #
    #   POLICY_EVAL_WRITE_FIXTURES=1 mix test test/postgres/fixtures_test.exs
    #
    """
  end
end
