# Renders a results file of dev/bench/presence.exs as one self-contained HTML page, with inline CSS
# and SVG and nothing loaded from the network.
#
#     mix run --no-start dev/bench/presence/report.exs results.json report.html
#
# The page has one bar chart for each figure of each window. A run made with `--compare` has the
# earlier figures and the changes in its results file. Each chart then shows the Rollcall figure of
# the earlier run next to the new one, and a table lists the changes. A run without Phoenix takes
# the Phoenix figures from the earlier run.
#
# The header of dev/bench/presence.exs explains the workload, the windows and the figures.

defmodule Report do
  @moduledoc false

  @metrics [{"reductions_per_s", "Reductions per second", :count}, {"memory_bytes", "Memory", :bytes}]
  @windows [{"join", "Join"}, {"steady", "Steady"}]

  def main([results_path, out_path]) do
    now = results_path |> File.read!() |> Jason.decode!()
    File.write!(out_path, page(now))
    IO.puts("Wrote #{out_path}")
  end

  ## Page

  defp page(now) do
    """
    <!doctype html>
    <html lang="en">
    <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Presence cost</title>
    <style>#{css()}</style>
    </head>
    <body>
    <main>
    <header>
      <p class="eyebrow">Realtime · presence</p>
      <h1>Presence cost: Rollcall and Phoenix</h1>
      <div class="chips">#{chips(now)}</div>
      <p class="meta">#{machine_line(now["machine"], now["started_at"])}</p>
    </header>
    #{Enum.map_join(@windows, "\n", &section(&1, now))}
    #{activity(now)}
    #{if now["comparison"], do: changes(now["comparison"]), else: ""}
    <footer>Each bar is the middle result of #{now["settings"]["repeats"]} repeats. Generated by dev/bench/presence/report.exs.</footer>
    </main>
    </body>
    </html>
    """
  end

  # The facts of the run that apply to the whole page.
  defp chips(now) do
    w = now["workload"]

    [
      "#{w["nodes"]} nodes",
      "Phoenix: #{w["shards"]} shards on each node",
      "every tenant on all #{w["nodes"]} nodes",
      "#{now["settings"]["repeats"]} repeats of each backend"
    ]
    |> Enum.map_join(&~s|<span class="chip">#{esc(&1)}</span>|)
  end

  # What happened in a window, in a sentence or two.
  defp what_happened("join", now) do
    w = now["workload"]

    "#{w["entries"]} entries join at once. The tenants: #{tenants(w["groups"])}. Entries are spread over topics, at most #{w["entries_per_topic"]} on each. The window ends when every node holds all the entries."
  end

  defp what_happened("steady", now) do
    w = now["workload"]
    changes = now["summary"] |> Map.values() |> hd() |> get_in(["steady", "operations", "median"])

    "For #{w["window_s"]} s, #{w["changes_per_s"]} changes happen each second across the cluster, which is #{w["changed_percent_per_s"]}% of the entries each second. A change picks an entry at random and either updates it or removes it and adds it back at once. The number of entries stays the same. About #{fmt(changes, :count)} changes in all."
  end

  defp caption("reductions_per_s", now) do
    "Work done by the Phoenix shards or the Rollcall trackers, all #{now["workload"]["nodes"]} nodes added together."
  end

  defp caption("memory_bytes", now) do
    "Memory of those processes plus the tables that hold the entries, all #{now["workload"]["nodes"]} nodes added together, after a garbage collection."
  end

  defp tenants(groups) do
    Enum.map_join(groups, " and ", fn g ->
      "#{g["tenants"]} #{plural(g["tenants"], "tenant")} with #{g["entries"]} entries on #{g["topics"]} #{plural(g["topics"], "topic")}"
    end)
  end

  defp plural(1, word), do: word
  defp plural(_, word), do: word <> "s"

  defp machine_line(machine, started_at) do
    [
      machine["cpu"],
      machine["schedulers"] && "#{machine["schedulers"]} schedulers",
      machine["otp"] && "OTP #{machine["otp"]}",
      started_at && String.slice(started_at, 0, 10)
    ]
    |> Enum.filter(& &1)
    |> Enum.map_join(" · ", &esc/1)
  end

  defp section({window, title}, now) do
    charts =
      for {metric, label, unit} <- @metrics do
        ~s|<div class="card"><h3>#{esc(label)}</h3><p class="caption">#{esc(caption(metric, now))}</p>#{chart(bars(now, window, metric), unit)}</div>|
      end

    ~s|<section><h2>#{title}</h2><p class="note">#{esc(what_happened(window, now))}</p><div class="pair">#{Enum.join(charts)}</div></section>|
  end

  ## Bars

  # The bars of one chart: Phoenix, then the Rollcall of the earlier run, then the Rollcall of this one.
  defp bars(now, window, metric) do
    baseline = now["baseline"]
    phoenix = stats(now, "phoenix", window, metric) || (baseline && stats(baseline, "phoenix", window, metric))
    before = baseline && stats(baseline, "rollcall", window, metric)
    current = stats(now, "rollcall", window, metric)

    Enum.filter(
      [
        phoenix && {"Phoenix", phoenix, "var(--phoenix)", 1.0},
        before && {"Rollcall baseline", before, "var(--brand)", 0.45},
        current && {if(baseline, do: "Rollcall now", else: "Rollcall"), current, "var(--brand)", 1.0}
      ],
      & &1
    )
  end

  defp stats(data, backend, window, metric), do: get_in(data, ["summary", backend, window, metric])

  @w 420
  @h 300
  @ml 58
  @mr 12
  @mt 26
  @mb 50

  defp chart(bars, unit) do
    plot_w = @w - @ml - @mr
    plot_h = @h - @mt - @mb
    ticks = bars |> Enum.map(fn {_, st, _, _} -> st["median"] end) |> Enum.max() |> ticks(unit)
    top = List.last(ticks)
    y = fn v -> @mt + plot_h - v / top * plot_h end
    slot = plot_w / length(bars)
    bar_w = min(64, slot * 0.6)

    grid =
      Enum.map_join(ticks, "", fn t ->
        ~s|<line class="gl" x1="#{@ml}" x2="#{@w - @mr}" y1="#{r(y.(t))}" y2="#{r(y.(t))}"/><text class="tick" x="#{@ml - 8}" y="#{r(y.(t) + 4)}" text-anchor="end">#{fmt(t, unit)}</text>|
      end)

    drawn =
      bars
      |> Enum.with_index()
      |> Enum.map_join("", fn {{name, st, color, opacity}, i} ->
        x = @ml + slot * i + (slot - bar_w) / 2
        mid = x + bar_w / 2

        ~s|<rect x="#{r(x)}" y="#{r(y.(st["median"]))}" width="#{r(bar_w)}" height="#{r(@mt + plot_h - y.(st["median"]))}" rx="3" fill="#{color}" fill-opacity="#{opacity}"/>| <>
          ~s|<text class="value" x="#{r(mid)}" y="#{r(y.(st["median"]) - 7)}" text-anchor="middle">#{fmt(st["median"], unit)}</text>| <>
          ~s|<text class="tick" x="#{r(mid)}" y="#{@h - @mb + 20}" text-anchor="middle">#{esc(name)}</text>|
      end)

    ~s|<svg viewBox="0 0 #{@w} #{@h}" role="img">#{grid}#{drawn}</svg>|
  end

  # Round ticks in the unit of the labels: MiB or KiB for bytes, so the ticks read 2, 4, 6 MiB.
  defp ticks(hi, unit) do
    scale = tick_scale(hi, unit)
    top = max(hi, 1) / scale
    raw = top / 4
    mag = :math.pow(10, Float.floor(:math.log10(raw)))
    step = Enum.find([1, 2, 5, 10], &(&1 * mag >= raw)) * mag
    for i <- 0..ceil(top / step), do: i * step * scale
  end

  defp tick_scale(hi, :bytes) when hi >= 1_048_576, do: 1_048_576
  defp tick_scale(hi, :bytes) when hi >= 1024, do: 1024
  defp tick_scale(_hi, _unit), do: 1

  ## Activity

  # What each window did. The reductions per second in the charts are the operations per second
  # multiplied by the reductions per operation, and this table shows both numbers.
  defp activity(now) do
    rows =
      for {backend, name} <- [{"phoenix", "Phoenix"}, {"rollcall", "Rollcall"}],
          {window, title} <- @windows,
          figures = get_in(now, ["summary", backend, window]) do
        median = fn key -> figures[key]["median"] end

        ~s|<tr><td>#{name}</td><td>#{title}</td><td class="num">#{r(median.("seconds"))} s</td><td class="num">#{whole(median.("operations"))}</td><td class="num">#{whole(median.("operations_per_s"))}</td><td class="num">#{whole(median.("reductions_per_operation"))}</td><td class="num">#{fmt(median.("reductions_per_s"), :count)}</td></tr>|
      end

    """
    <section><h2>What each window did</h2>
    <p class="note">An operation is an entry that joins, in the join window, or a change, in the steady window. The reductions per second in the charts are the operations per second multiplied by the reductions per operation. The steady window also pays for the heartbeats, which happen whether or not anything changes. The join window includes a short wait after the entries have joined.</p>
    <div class="card"><div class="scroll"><table>
    <thead><tr><th>Backend</th><th>Window</th><th class="num">Length</th><th class="num">Operations</th><th class="num">Operations per second</th><th class="num">Reductions per operation</th><th class="num">Reductions per second</th></tr></thead>
    <tbody>#{Enum.join(rows)}</tbody>
    </table></div></div></section>
    """
  end

  ## Changes

  # The rows come from the results file, where the runner worked out each change.
  defp changes(comparison) do
    rows =
      for row <- comparison do
        {_, label, unit} = List.keyfind(@metrics, row["metric"], 0)
        {_, title} = List.keyfind(@windows, row["window"], 0)

        ~s|<tr><td>#{esc(String.capitalize(row["backend"]))}</td><td>#{title}</td><td>#{esc(label)}</td><td class="num">#{fmt(row["before"], unit)}</td><td class="num">#{fmt(row["now"], unit)}</td><td class="num">#{r(row["percent"])}%</td></tr>|
      end

    """
    <section><h2>Change against the earlier run</h2>
    <div class="card"><div class="scroll"><table>
    <thead><tr><th>Backend</th><th>Window</th><th>Figure</th><th class="num">Before</th><th class="num">Now</th><th class="num">Change</th></tr></thead>
    <tbody>#{Enum.join(rows)}</tbody>
    </table></div></div></section>
    """
  end

  ## Formatting

  defp fmt(v, :bytes) when v >= 1_048_576, do: "#{trim(v / 1_048_576)} MiB"
  defp fmt(v, :bytes) when v >= 1024, do: "#{trim(v / 1024)} KiB"
  defp fmt(v, :bytes), do: "#{trim(v)} B"
  defp fmt(v, :count) when v >= 1_000_000, do: "#{trim(v / 1_000_000)}M"
  defp fmt(v, :count) when v >= 1000, do: "#{trim(v / 1000)}k"
  defp fmt(v, :count), do: trim(v)

  defp trim(v) do
    v
    |> Kernel./(1)
    |> :erlang.float_to_binary(decimals: if(v >= 100, do: 0, else: 1))
    |> String.replace(~r/\.0$/, "")
  end

  defp whole(v) do
    v
    |> round()
    |> Integer.to_string()
    |> String.reverse()
    |> String.replace(~r/(\d{3})(?=\d)/, "\\1,")
    |> String.reverse()
  end

  defp r(v), do: :erlang.float_to_binary(v / 1, decimals: 1)

  defp esc(value) do
    value
    |> to_string()
    |> String.replace("&", "&amp;")
    |> String.replace("<", "&lt;")
    |> String.replace(">", "&gt;")
    |> String.replace("\"", "&quot;")
  end

  ## Style

  defp css do
    """
    :root {
      --bg: #1c1c1c; --panel: #232323; --panel-2: #2a2a2a; --border: #2e2e2e; --grid: #333333;
      --text: #ededed; --muted: #a0a0a0; --brand: #3ecf8e; --phoenix: #f5a524;
      --font: "Circular", ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
      --mono: "Source Code Pro", ui-monospace, "SF Mono", Menlo, Consolas, monospace;
    }
    * { box-sizing: border-box; }
    body { margin: 0; background: var(--bg); color: var(--text); font-family: var(--font); line-height: 1.55; -webkit-font-smoothing: antialiased; }
    main { max-width: 960px; margin: 0 auto; padding: 48px 16px 72px; }
    .eyebrow { margin: 0 0 10px; color: var(--brand); font-size: 13px; letter-spacing: .08em; text-transform: uppercase; font-weight: 600; }
    h1 { margin: 0 0 14px; font-size: clamp(28px, 5vw, 40px); line-height: 1.1; letter-spacing: -.02em; font-weight: 600; }
    h2 { margin: 0 0 6px; font-size: 22px; letter-spacing: -.01em; font-weight: 600; }
    h3 { margin: 0 0 4px; font-size: 14px; font-weight: 600; color: var(--text); }
    .caption { margin: 0 0 8px; color: var(--muted); font-size: 12px; line-height: 1.45; }
    section { margin-top: 44px; }
    .note { margin: 0 0 14px; color: var(--muted); max-width: 70ch; }
    .meta { margin: 8px 0 0; color: var(--muted); font: 13px var(--mono); }
    .chips { display: flex; flex-wrap: wrap; gap: 6px; }
    .chip { padding: 2px 8px; border: 1px solid var(--border); border-radius: 999px; background: var(--panel-2); color: var(--muted); font: 12px var(--mono); }
    .pair { display: grid; grid-template-columns: repeat(auto-fit, minmax(300px, 1fr)); gap: 12px; }
    .card { background: var(--panel); border: 1px solid var(--border); border-radius: 10px; padding: 18px; }
    svg { display: block; width: 100%; height: auto; }
    line.gl { stroke: var(--grid); stroke-width: 1; }
    .tick { fill: var(--muted); font: 11px var(--mono); }
    .value { fill: var(--text); font: 12px var(--mono); }
    .scroll { overflow-x: auto; }
    table { width: 100%; border-collapse: collapse; font-size: 13px; }
    th, td { padding: 8px 10px; border-bottom: 1px solid var(--border); text-align: left; white-space: nowrap; }
    th { color: var(--muted); font-weight: 500; }
    td.num, th.num { text-align: right; font-family: var(--mono); }
    footer { margin-top: 48px; color: var(--muted); font-size: 12px; }
    """
  end
end

Report.main(System.argv())
